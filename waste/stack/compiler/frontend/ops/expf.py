from buddy_mlir import ir
from buddy_mlir.dialects import arith, math


def exp_f32(value):
    """Emit a fixed FP32 exp approximation before activation rounding."""
    f32 = ir.F32Type.get()
    i32 = ir.IntegerType.get_signless(32)

    def constant(number):
        return arith.ConstantOp(f32, float(number)).result

    zero = constant(0.0)
    lower = constant(-104.0)
    upper = constant(100.0)
    is_nan = arith.CmpFOp(arith.CmpFPredicate.UNO, value, value).result
    underflow = arith.CmpFOp(arith.CmpFPredicate.OLT, value, lower).result
    overflow = arith.CmpFOp(arith.CmpFPredicate.OGT, value, upper).result
    # Bound the exponent conversion, including NaN and infinity inputs.
    bounded = arith.SelectOp(underflow, lower, value).result
    bounded = arith.SelectOp(overflow, upper, bounded).result
    bounded = arith.SelectOp(is_nan, zero, bounded).result
    rounded = math.RoundEvenOp(
        arith.MulFOp(bounded, constant(1.4426950408889634)).result
    ).result
    exponent = arith.FPToSIOp(i32, rounded).result
    residual = math.FmaOp(rounded, constant(-0.693145751953125), bounded).result
    residual = math.FmaOp(rounded, constant(-1.428606765330187e-6), residual).result
    polynomial = constant(0.00019852761761285365)
    for coefficient in (
        0.0013930435525253415,
        0.008333360776305199,
        0.041666485369205475,
        0.1666666716337204,
        0.5,
    ):
        polynomial = math.FmaOp(polynomial, residual, constant(coefficient)).result
    square = arith.MulFOp(residual, residual).result
    polynomial = arith.AddFOp(
        constant(1.0), math.FmaOp(square, polynomial, residual).result
    ).result

    one = arith.ConstantOp(i32, 1).result
    bias = arith.ConstantOp(i32, 127).result
    shift = arith.ConstantOp(i32, 23).result
    half = arith.ShRSIOp(exponent, one).result
    remainder = arith.SubIOp(exponent, half).result
    for power in (half, remainder):
        bits = arith.ShLIOp(arith.AddIOp(power, bias).result, shift).result
        factor = arith.BitcastOp(f32, bits).result
        polynomial = arith.MulFOp(polynomial, factor).result
    result = arith.SelectOp(underflow, zero, polynomial).result
    result = arith.SelectOp(overflow, constant(float("inf")), result).result
    return arith.SelectOp(is_nan, value, result).result
