#!/usr/bin/env python3
"""Writes vectors.h: the bank images of the mxint8quantize C tests, the
expected output computed offline by quantize_mxint8 of
stack/compiler/frontend/quant.py.

    nix develop -c python3 examples/prefab/balls/mxint8quantize/workloads/ctests/vectors.py

A test moves <case>_input into the input bank, runs one MXINT8QUANT and moves
the output bank back; its packed rows (from bank row <CASE>_OUT_BASE) must
equal <case>_expected byte for byte, zero padding included. The output is a
new version of its bank: rows outside the packed rows are undefined.
"""

import sys
from pathlib import Path

import numpy as np
import torch

here = Path(__file__).resolve().parent
repo = here.parents[5]
sys.path[:0] = [
    str(repo / "stack/thirdparty/buddy-mlir/build/python_packages"),
    str(repo / "stack"),
]
from compiler.frontend.quant import quantize_mxint8  # noqa: E402


def packed_rows(k):
    return k // 16 + (k + 511) // 512


def array(ctype, name, data):
    words = ", ".join(f"0x{int(v):x}" for v in data)
    return f"static const {ctype} {name}[{len(data)}] __attribute__((aligned(64))) = {{{words}}};\n"


def case(name, bits, in_base, out_base):
    """bits: [rows, k] uint32 FP32 bit patterns."""
    rows, k = bits.shape
    values = torch.from_numpy(bits.view(np.float32).copy())
    packed = quantize_mxint8(values, -1).view(torch.uint8).numpy()
    stride = packed_rows(k)
    # NaN before the input rows: the Ball must not read them.
    image = np.full(in_base * 4 + rows * k, 0x7FC00000, np.uint32)
    image[in_base * 4 :] = bits.reshape(-1)
    expected = np.zeros((rows, stride * 16), np.uint8)
    expected[:, : packed.shape[1]] = packed
    upper = name.upper()
    return (
        f"#define {upper}_ROWS {rows}\n#define {upper}_K {k}\n"
        f"#define {upper}_IN_BASE {in_base}\n#define {upper}_OUT_BASE {out_base}\n"
        f"#define {upper}_IN_ROWS {in_base + rows * k // 4}\n#define {upper}_OUT_ROWS {out_base + rows * stride}\n"
        + array("uint32_t", f"{name}_input", image)
        + array("uint8_t", f"{name}_expected", expected.reshape(-1))
    )


def f32(values):
    return np.array(values, np.float32).view(np.uint32)


def edges():
    row0 = np.concatenate(
        [
            # Block 0: the maximum 127.5 gives e = 0; RNE ties, the clamp at 127,
            # signed zeros and subnormals that vanish.
            f32(
                [
                    127.5,
                    -127.5,
                    0.5,
                    1.5,
                    2.5,
                    -2.5,
                    3.5,
                    -0.5,
                    0.0,
                    -0.0,
                    1.0,
                    -1.0,
                    0.49999997,
                    126.49999,
                    64.0,
                    -64.0,
                ]
            ),
            np.array([1, 0x80000001, 0x007FFFFF, 0x00800000], np.uint32),
            f32(np.linspace(-100, 100, 12)),
            # Block 1: the largest finite magnitudes, e = 121.
            f32([3.4028235e38, -3.4028235e38, 1e38, -2.5e37, 1.0, 0.0]),
            f32(np.linspace(-3e38, 3e38, 26)),
        ]
    )
    rng = np.random.default_rng(7)
    row1 = np.concatenate(
        [
            f32([0.0, -0.0] * 16),  # An all-zero block: byte 127, codes 0.
            rng.integers(0, 0x00800000, 32, dtype=np.uint32)  # Subnormals: e = -127.
            | (rng.integers(0, 2, 32, dtype=np.uint32) << 31),
        ]
    )
    # Block 0: small normals whose exponent field is below 6, e = -127.
    # Block 1: magnitudes 63.5 .. 64.5 around the code 64 ties.
    row2 = np.concatenate(
        [
            (rng.integers(0, 0x02800000, 32, dtype=np.uint32))
            | (rng.integers(0, 2, 32, dtype=np.uint32) << 31),
            f32(np.linspace(-64.5, 64.5, 32) * 4.0),
        ]
    )
    return np.stack([row0, row1, row2]).astype(np.uint32)


def randoms():
    rng = np.random.default_rng(11)
    rows, k = 3, 544
    scale = np.exp2(rng.integers(-40, 40, (rows, k // 32, 1))).astype(np.float32)
    values = (rng.standard_normal((rows, k // 32, 32)) * scale).astype(np.float32)
    return values.reshape(rows, k).view(np.uint32)


def main():
    text = (
        "/* Generated by vectors.py from quant.py quantize_mxint8. Do not edit. */\n"
        "#pragma once\n#include <stdint.h>\n"
        + case("quant_edges", edges(), 3, 2)
        + case("quant_random", randoms(), 0, 0)
    )
    (here / "vectors.h").write_text(text)


if __name__ == "__main__":
    main()
