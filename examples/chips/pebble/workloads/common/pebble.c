void pebble_print_i8_matrix(const char *name, const elem_t *matrix, int rows,
                            int cols) {
  printf("Matrix %s (%dx%d):\n", name, rows, cols);
  for (int row = 0; row < rows; ++row) {
    for (int col = 0; col < cols; ++col) {
      printf("%4d ", (int)matrix[row * cols + col]);
    }
    printf("\n");
  }
  printf("\n");
}

void pebble_print_i32_matrix(const char *name, const result_t *matrix, int rows,
                             int cols) {
  printf("Matrix %s (%dx%d):\n", name, rows, cols);
  for (int row = 0; row < rows; ++row) {
    for (int col = 0; col < cols; ++col) {
      printf("%6d ", (int)matrix[row * cols + col]);
    }
    printf("\n");
  }
  printf("\n");
}
