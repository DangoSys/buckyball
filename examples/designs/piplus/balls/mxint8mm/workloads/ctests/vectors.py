#!/usr/bin/env python3
"""Writes vectors.h: the operands and expected results of the mxint8mm C
tests. A and B are packed by quantize_mxint8 of
stack/compiler/frontend/quant.py; C follows the Ball's accumulation order:
per element, block by block, t = fp32(p * 2^(ea + eb)) and acc = fp32(acc + t)
from +0.0 or the old C.

    nix develop -c python3 examples/designs/piplus/balls/mxint8mm/workloads/ctests/vectors.py
"""

import sys
from pathlib import Path

import numpy as np
import torch

here = Path(__file__).resolve().parent
repo = here.parents[6]
sys.path[:0] = [
    str(repo / "stack/thirdparty/buddy-mlir/build/python_packages"),
    str(repo / "stack/compiler"),
]
from frontend.quant import quantize_mxint8  # noqa: E402


def packed_rows(k):
    return k // 16 + (k + 511) // 512


def image(packed, base):
    """Bank image of packed MXINT8 rows from bank row `base`."""
    rows, length = packed.shape
    stride = packed_rows(length * 32 // 33) * 16
    out = np.zeros((base * 16 + rows * stride,), np.uint8)
    for row in range(rows):
        start = base * 16 + row * stride
        out[start : start + length] = packed[row]
    return out


def product(a, b, old):
    k = a.shape[1] * 32 // 33
    codes_a, codes_b = a[:, :k].view(np.int8).astype(np.int64), b[:, :k].view(
        np.int8
    ).astype(np.int64)
    exp_a, exp_b = a[:, k:].astype(np.int64), b[:, k:].astype(np.int64)
    c = old.copy()
    for m in range(a.shape[0]):
        for n in range(b.shape[0]):
            acc = c[m, n]
            for block in range(k // 32):
                lanes = slice(block * 32, block * 32 + 32)
                p = int((codes_a[m, lanes] * codes_b[n, lanes]).sum())
                term = np.float32(
                    np.float64(p)
                    * np.ldexp(1.0, int(exp_a[m, block] + exp_b[n, block] - 254))
                )
                acc = np.float32(acc + term)
                assert np.isfinite(term) and np.isfinite(acc)
            c[m, n] = acc
    return c


def array(ctype, name, data, qualifier="const "):
    words = ", ".join(f"0x{int(v):x}" for v in data)
    return f"static {qualifier}{ctype} {name}[{len(data)}] __attribute__((aligned(64))) = {{{words}}};\n"


def case(name, a, b, bases, old=None):
    m, n = a.shape[0], b.shape[0]
    pa = quantize_mxint8(torch.from_numpy(a), -1).view(torch.uint8).numpy()
    pb = quantize_mxint8(torch.from_numpy(b), -1).view(torch.uint8).numpy()
    initial = np.zeros((m, n), np.float32) if old is None else old
    expected = product(pa, pb, initial)
    c_image = np.zeros(bases[2] * 4 + m * n, np.float32)
    c_image[bases[2] * 4 :] = initial.reshape(-1)
    upper = name.upper()
    return (
        f"#define {upper}_M {m}\n#define {upper}_N {n}\n#define {upper}_K {a.shape[1]}\n"
        f"#define {upper}_A_BASE {bases[0]}\n#define {upper}_B_BASE {bases[1]}\n"
        f"#define {upper}_C_BASE {bases[2]}\n#define {upper}_ACCUMULATE {int(old is not None)}\n"
        + array("uint8_t", f"{name}_a", image(pa, bases[0]))
        + array("uint8_t", f"{name}_b", image(pb, bases[1]))
        + array("uint32_t", f"{name}_c", c_image.view(np.uint32), "")
        + array("uint32_t", f"{name}_expected", expected.reshape(-1).view(np.uint32))
    )


def normal(rng, rows, k, spread):
    scale = np.exp2(rng.integers(-spread, spread, (rows, k // 32, 1))).astype(
        np.float32
    )
    return (
        (rng.standard_normal((rows, k // 32, 32)) * scale)
        .astype(np.float32)
        .reshape(rows, k)
    )


def extremes():
    rng = np.random.default_rng(5)
    a = normal(rng, 3, 64, 2)
    b = normal(rng, 4, 64, 2)
    # Row 0: subnormal elements, block exponent -127: subnormal and zero terms.
    a[0] = (rng.standard_normal(64) * 1e-39).astype(np.float32)
    b[0] = (rng.standard_normal(64) * 1e-39).astype(np.float32)
    b[1] = (rng.standard_normal(64) * 1e-30).astype(np.float32)
    # Row 1: two blocks with opposite products cancel to +0.
    a[1, 32:] = -a[1, :32]
    b[2, 32:] = b[2, :32]
    # Row 2 x B row 3: products near the top of the FP32 range.
    a[2] = (rng.standard_normal(64) * 1e18).astype(np.float32)
    b[3] = (rng.standard_normal(64) * 1e18).astype(np.float32)
    return a, b


def main():
    rng = np.random.default_rng(3)
    text = (
        "/* Generated by vectors.py. Do not edit. */\n#pragma once\n#include <stdint.h>\n"
        + case("mm_small", normal(rng, 3, 64, 8), normal(rng, 8, 64, 8), (1, 2, 3))
        + case(
            "mm_accumulate",
            normal(rng, 5, 96, 20),
            normal(rng, 12, 96, 20),
            (0, 0, 0),
            (rng.standard_normal((5, 12)) * 1e3).astype(np.float32),
        )
        + case("mm_extremes", *extremes(), (0, 0, 0))
    )
    (here / "vectors.h").write_text(text)


if __name__ == "__main__":
    main()
